/**
 * Node checks for the map loading screens. Run from the repo root with plain node:
 *
 *   node tests/features/loading-screens.mjs
 *
 * The owner: "add a cool loading screen for maps thats 3 seconds like the
 * fortnite one". What node can see:
 *
 *   1. THE PICTURES. Every map in maps.js has assets/loading/<id>.jpg, a real
 *      JPEG between 1280 and 1920 px wide, 16:9, at most 250 KB. No file is
 *      there for a map that does not exist (a leftover from a retired one).
 *   2. THE TIPS. Every {action} in a tip is a real action in the key registry
 *      (flight/input.js) and is one the tip's game has (a boat tip names boat
 *      keys). Every tip renders to plain words with no braces left, and a
 *      player who unbinds a key does not get told to press a dash. Tips go
 *      round in order, not the same one twice running.
 *   3. THE CREDIT. A map that says it is OpenStreetMap's gets the line
 *      "© OpenStreetMap contributors"; a map that does not, none.
 *   4. THE NUMBERS. About three seconds, a skip after one, fades that cannot
 *      flash (a third of a second at the least).
 *   5. THE WIRING, read as text: the feature is in the plug-in list, the
 *      world builds in as many steps as the screen is told it has, the
 *      drives that buttons start go through launchDrive, and the offline
 *      list names the new modules and every picture.
 *
 * The browser half (loading-screens.browser.js) puts the screen up in the
 * real game: it shows on a map start, a key skips it only after a second, and
 * it goes when the loading is done.
 *
 * Exit code 1 if anything fails.
 */

import { readFileSync, existsSync, statSync, readdirSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const load = (p) => import(new URL(p, root).href);
const text = (p) => readFileSync(new URL(p, root), 'utf8');

const results = [];
const ok = (name, pass, detail = '') => results.push({ name, pass: !!pass, detail: String(detail) });

/** Width, height of a baseline or progressive JPEG, from its first SOF marker. */
export function jpegSize(buf) {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null;
  let i = 2;
  while (i + 9 < buf.length) {
    if (buf[i] !== 0xff) {
      i++;
      continue;
    }
    const m = buf[i + 1];
    if (m === 0xff) {
      i++;
      continue;
    }
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) {
      return { h: (buf[i + 5] << 8) | buf[i + 6], w: (buf[i + 7] << 8) | buf[i + 8] };
    }
    i += 2 + ((buf[i + 2] << 8) | buf[i + 3]);
  }
  return null;
}

const { MAPS } = await load('src/world/maps.js');
const KB = 1024;
const MAX_BYTES = 250 * KB;

/* ---------------- 1. the pictures ---------------- */

const missing = [];
const heavy = [];
const odd = [];
let bytes = 0;
for (const m of MAPS) {
  const p = `assets/loading/${m.id}.jpg`;
  if (!existsSync(new URL(p, root))) {
    missing.push(m.id);
    continue;
  }
  const buf = readFileSync(new URL(p, root));
  bytes += buf.length;
  if (buf.length > MAX_BYTES) heavy.push(`${m.id} ${Math.round(buf.length / KB)} KB`);
  const sz = jpegSize(buf);
  if (!sz) odd.push(`${m.id} is not a JPEG`);
  else if (sz.w < 1280 || sz.w > 1920 || Math.abs(sz.w / sz.h - 16 / 9) > 0.02) odd.push(`${m.id} ${sz.w}x${sz.h}`);
}
ok(`every one of the ${MAPS.length} maps has a loading picture (assets/loading/<id>.jpg)`, missing.length === 0, missing.join(', ') || `${MAPS.length} pictures, ${(bytes / KB / KB).toFixed(1)} MB in all`);
ok('no picture is over 250 KB', heavy.length === 0, heavy.join(', ') || 'all under');
ok('every picture is a JPEG, 1280-1920 px wide and 16:9', odd.length === 0, odd.join(', ') || 'all fit');
const ids = new Set(MAPS.map((m) => m.id));
let files = [];
try {
  files = readdirSync(new URL('assets/loading/', root)).filter((f) => f.endsWith('.jpg'));
} catch (e) {
  files = [];
}
const strays = files.filter((f) => !ids.has(f.replace(/\.jpg$/, '')));
ok('no picture is for a map that is not in the game', strays.length === 0, strays.join(', ') || 'none');

// Where each picture's subject is, for a phone held upright (generated by tools/loading-art/capture.mjs).
const { FOCUS } = await load('src/ui/loading-focus.js');
const noFocus = MAPS.filter((m) => !(Array.isArray(FOCUS[m.id]) && FOCUS[m.id].length === 2 && FOCUS[m.id].every((v) => v >= 0 && v <= 100))).map((m) => m.id);
ok('every picture says where its subject is, so a phone held upright crops round it', noFocus.length === 0, noFocus.join(', ') || `${MAPS.length} subjects placed`);
const strayFocus = Object.keys(FOCUS).filter((id) => !ids.has(id));
ok('and none is for a map that is not in the game', strayFocus.length === 0, strayFocus.join(', ') || 'none');

/* ---------------- 2. the tips ---------------- */

if (typeof globalThis.document === 'undefined') {
  Object.defineProperty(globalThis, 'document', {
    configurable: true,
    value: { createElement: () => ({ getContext: () => null, width: 0, height: 0, style: {} }), body: { appendChild() {} } },
  });
}
const T = await load('src/ui/loading-tips.js');
const I = await load('src/flight/input.js');
const { ACTIONS } = I;
const badAction = [];
const wrongGame = [];
const long = [];
let count = 0;
for (const game of T.TIP_GAMES) {
  const ctx = T.TIP_CONTEXT[game];
  for (const tip of T.tipsFor(game)) {
    count++;
    if (tip.length > 120) long.push(`"${tip.slice(0, 30)}…" is ${tip.length}`);
    for (const a of T.tipActions(tip)) {
      if (!ACTIONS[a]) badAction.push(`${game}: {${a}}`);
      else if (!ACTIONS[a].ctx.includes(ctx)) wrongGame.push(`${game}: {${a}} is for ${ACTIONS[a].ctx.join('/')}`);
    }
  }
}
ok(`every key in a tip is an action in the registry (${count} tips)`, badAction.length === 0, badAction.join(', ') || 'all real');
ok('every tip names only keys its own game has', wrongGame.length === 0, wrongGame.join('; ') || 'all fit');
ok('every tip is short enough to read in three seconds (120 characters)', long.length === 0, long.join('; ') || 'all short');
ok('each game has at least six tips of its own', T.TIP_GAMES.every((g) => T.TIP_LISTS[g].length >= 6), T.TIP_GAMES.map((g) => `${g} ${T.TIP_LISTS[g].length}`).join(', '));

const keyOf = (a) => I.keyName(a, null);
const rendered = T.TIP_GAMES.flatMap((g) => T.tipsFor(g).map((t) => T.renderTip(t, keyOf)));
ok('every tip renders to plain words, no braces left', rendered.every((t) => !/[{}]/.test(t)), rendered.find((t) => /[{}]/.test(t)) || `${rendered.length} rendered`);
ok('the default keys are in the words (landing gear is G, power is Shift)',
  T.renderTip('Landing gear is {gear}.', keyOf) === 'Landing gear is G.' && /Shift/.test(T.renderTip('Hold {throttleUp}.', keyOf)),
  T.renderTip('Landing gear is {gear}. Hold {throttleUp}.', keyOf));
ok('a key the player moved is the key named', T.renderTip('Landing gear is {gear}.', () => 'L') === 'Landing gear is L.');
const un = T.renderTip('Press {gear} to put the wheels down.', () => '—');
ok('an unbound key is not shown as a dash', !/—/.test(un) && /key/.test(un), un);
const mem = {};
const seq = Array.from({ length: 5 }, () => T.nextTip('boat', mem, () => 0.4).index);
ok('tips go round in order and never repeat back to back', seq.every((v, i) => i === 0 || v === (seq[i - 1] + 1) % T.tipsFor('boat').length), seq.join(','));

/* ---------------- 3. the credit ---------------- */

const stub = (name, value) => {
  if (typeof globalThis[name] === 'undefined') Object.defineProperty(globalThis, name, { configurable: true, value });
};
stub('window', {});
stub('navigator', { userAgent: 'node' });
stub('localStorage', { getItem: () => null, setItem() {}, removeItem() {} });
stub('location', { search: '' });
const L = await load('src/features/loading-screens.js');
ok('a map with osm: true shows © OpenStreetMap contributors', L.attributionFor({ id: 'x', osm: true }) === '© OpenStreetMap contributors', L.attributionFor({ id: 'x', osm: true }));
ok('a map that gives its own credit line shows that line', L.attributionFor({ id: 'x', attribution: '© OpenStreetMap contributors · USGS' }) === '© OpenStreetMap contributors · USGS');
ok('the real-world San Francisco Bay map is credited even before it says so', L.attributionFor({ id: 'sfbay' }) === '© OpenStreetMap contributors');
ok('none of today\'s maps carries a credit it does not owe', MAPS.every((m) => L.attributionFor(m) === null), MAPS.filter((m) => L.attributionFor(m)).map((m) => m.id).join(', ') || 'none');
ok('a map\'s picture is assets/loading/<id>.jpg', L.artPath('kestrel') === 'assets/loading/kestrel.jpg');
ok('a map with no sea colour still gets a gradient', /gradient/.test(L.fallbackFor({})) && /gradient/.test(L.fallbackFor(MAPS[0])));

/* ---------------- 4. the numbers ---------------- */

const C = L.LOADING_CONFIG;
ok('about three seconds at the least', C.minMs >= 3000 && C.minMs <= 3500, `${C.minMs} ms`);
ok('a key or a tap skips it after one second', C.skipAfterMs === 1000, `${C.skipAfterMs} ms`);
ok('the fades are at least a third of a second (nothing can flash)', C.fadeInMs >= 300 && C.fadeOutMs >= 300, `in ${C.fadeInMs} ms, out ${C.fadeOutMs} ms`);
ok('a tip stays long enough to read', C.tipEveryMs >= 3500, `${C.tipEveryMs} ms`);

/* ---------------- 5. the wiring ---------------- */

const main = text('src/main.js');
const steps = (main.match(/yield next\(/g) || []).length;
const declared = Number((main.match(/const STEPS = (\d+);/) || [])[1]);
ok('the world builds in exactly as many steps as the screen is told it has', steps === declared && steps > 0, `${steps} yields, STEPS = ${declared}`);
ok('buildWorld() still builds it all in one go (it drains the steps)', /buildWorld\(quality\) \{[^}]*buildWorldSteps\(quality\)[^}]*\.next\(\)\.done/s.test(main));
ok('the frame loop draws nothing while the world is half built', /if \(this\._worldBuilding\)/.test(main));
ok('the drives that buttons start go through launchDrive; startDrive stays synchronous', (main.match(/this\.launchDrive\(/g) || []).length >= 3 && /^  startDrive\(kind = 'boat', opts = \{\}\) \{/m.test(main));
ok('the plug-in list loads the feature', /import '\.\/loading-screens\.js';/.test(text('src/features/index.js')));
const sw = text('sw.js');
for (const f of ['src/features/loading-screens.js', 'src/ui/loading-screen.js', 'src/ui/loading-tips.js', 'src/ui/loading-focus.js']) {
  ok(`the offline list names ${f}`, sw.includes(`'${f}'`));
}
const noArt = MAPS.filter((m) => !sw.includes(`'assets/loading/${m.id}.jpg'`)).map((m) => m.id);
ok('the offline list names every map\'s picture', noArt.length === 0, noArt.join(', ') || `${MAPS.length} listed`);
// The code, without its comments (which say what they are not).
const code = (p) => text(p).replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
ok('no sound anywhere in the screen (no audio, no Audio, no play())', !/AudioContext|new Audio|\.play\(|audio\./.test(code('src/ui/loading-screen.js') + code('src/ui/loading-tips.js') + code('src/features/loading-screens.js')));
ok('the screen never uses requestAnimationFrame (the suites freeze it)', !/requestAnimationFrame/.test(code('src/ui/loading-screen.js')));

/* ---------------- report ---------------- */

const failed = results.filter((r) => !r.pass);
if (!process.argv.includes('--quiet')) for (const r of results) console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${r.name}${r.detail ? ` — ${r.detail}` : ''}`);
else for (const r of failed) console.log(`FAIL  ${r.name} — ${r.detail}`);
console.log(`${results.length - failed.length}/${results.length} checks passed`);
process.exit(failed.length ? 1 : 0);
