/* ---------------- traffic name tags ---------------- */
{
  const THREE = await load('src/vendor/three.module.js');
  const TR = await load('src/features/traffic.js');
  const cam = new THREE.PerspectiveCamera(60, 16 / 9, 1, 30000);
  cam.position.set(0, 3, 0);
  cam.lookAt(0, 3, -1000);
  cam.updateMatrixWorld();
  const tag = (x, z, dist) => {
    const sp = new THREE.Sprite(new THREE.SpriteMaterial());
    sp.scale.set(0.18, 0.045, 1);
    sp.position.set(x, 10, z);
    sp.visible = true;
    return { tag: sp, tagW: 0.8, dist };
  };
  // Two aeroplanes on neighbouring stands, 1.5 km off, 40 m apart: one patch of screen.
  const near = tag(0, -1500, 1500);
  const far = tag(40, -1540, 1540);
  const apart = tag(-700, -1500, 1650);
  const hid = TR.declutterTags([far, near, apart], cam);
  ok('tags: two that cover each other — the nearer stays, the farther is hidden', near.tag.visible && !far.tag.visible && hid === 1, `${hid} hidden`);
  ok('tags: one clear of the others stays', apart.tag.visible);
  const src = read('src/features/traffic.js');
  ok('tags: drawn over the world, not sliced by a hangar roof (depthTest off)', /SpriteMaterial\(\{ map: tex, transparent: true, depthWrite: false, depthTest: false/.test(src));
  // From the seat they take the depth test again, like the nav rails (navguide.js setOccluded).
  const both = [near, far, apart];
  for (const t of both) t.tag.material.depthTest = false;
  const n1 = TR.tagsOccluded(both, true);
  const inSeat = both.every((t) => t.tag.material.depthTest === true);
  const n0 = TR.tagsOccluded(both, true);
  TR.tagsOccluded(both, false);
  const outside = both.every((t) => t.tag.material.depthTest === false);
  ok('tags: in the cockpit view the panel and frames hide them; outside they draw over the world', inSeat && outside && n1 === 3 && n0 === 0, `${n1} switched, then ${n0}`);
  ok('tags: the traffic update tells them when you are in the seat', /tagsOccluded\(T\.list, !!\(sim\.rig && sim\.rig\.mode === 'cockpit' && sim\.cockpit && sim\.cockpit\.visible\)\)/.test(src));
}

