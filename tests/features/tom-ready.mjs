/* ---------------- the wheel brakes ---------------- */
{
  const THREE = await load('src/vendor/three.module.js');
  const T = await load('src/world/terrain.js');
  const P = await load('src/aircraft/physics.js');
  const { Weather } = await load('src/world/weather.js');
  T.applyMap('kestrel');
  const weather = new Weather();
  weather.load({ time: 'day', condition: 'clear', windSpeedKts: 0, windDirDeg: 90 });
  const STEP = 1 / 60;
  // Rolling east at `v` m/s at idle, brakes `b` (both, or left/right toe brakes); seconds to stop, and the trace.
  const brake = (id, v, b, secs, toe = null) => {
    P.applyAircraft(id);
    const ac = new P.Aircraft();
    ac.mode = 'normal';
    ac.reset({ pos: new THREE.Vector3(-400, 0, 0), headingDeg: 90, speed: v, altAGL: null, engineOn: true, gearDown: true, fuel: 0.6 });
    ac.parkingBrake = false;
    let stop = null;
    let maxJerk = 0;
    let prev = ac.groundSpeed;
    const h0 = ac.heading;
    for (let t = 0; t < secs; t += STEP) {
      ac.controls.throttle = 0;
      ac.controls.brakes = b;
      if (toe) { ac.controls.brakeL = toe[0]; ac.controls.brakeR = toe[1]; }
      ac.update(STEP, weather);
      const gs = ac.groundSpeed;
      if (t > 0.5) maxJerk = Math.max(maxJerk, Math.abs(gs - prev));
      prev = gs;
      if (stop === null && gs < 0.3) stop = t;
    }
    return { stop, gs: ac.groundSpeed, crashed: ac.crashed, turned: ((ac.heading - h0 + 540) % 360) - 180, maxJerk };
  };
  const a = brake('a321', 12, 1, 12);
  ok('brakes: an A321neo at 12 m/s, idle, full brakes, stops (it crept on for ever)', a.stop !== null && a.stop < 7 && a.gs < 0.3 && !a.crashed, `stopped at ${a.stop && a.stop.toFixed(1)} s, ${a.gs.toFixed(2)} m/s`);
  const half = brake('a321', 12, 0.5, 15);
  ok('brakes: half brakes stop it too, more gently', half.stop !== null && half.stop > a.stop, `stopped at ${half.stop && half.stop.toFixed(1)} s`);
  const held = brake('a321', 0.5, 1, 20);
  ok('brakes: held on at idle, it does not creep', held.gs < 0.15, `${held.gs.toFixed(3)} m/s after 20 s`);
  ok('brakes: no chatter as it stops (speed changes smoothly)', a.maxJerk < 0.5 && held.maxJerk < 0.5, `${a.maxJerk.toFixed(3)}, ${held.maxJerk.toFixed(3)} m/s a step`);
  const fast = brake('a321', 60, 1, 4);
  const fastWas = 60 - fast.gs;
  ok('brakes: at speed the most a brake does (grip, tipping) is unchanged — still no more than about half a g', fastWas / 4 < 0.6 * 9.81, `${(fastWas / 4).toFixed(2)} m/s² over 4 s`);
  const right = brake('a321', 6, 0, 6, [0, 0.8]);
  ok('brakes: the right toe brake alone still turns her right on the ground', right.turned > 1, `${right.turned.toFixed(1)}°`);
  // Taxiing: a turn on the pedals, then let go — the heading the ground assist holds is the new one.
  const taxi = (mode) => {
    P.applyAircraft('a321');
    const ac = new P.Aircraft();
    ac.mode = mode;
    ac.reset({ pos: new THREE.Vector3(-400, 0, 0), headingDeg: 90, speed: 0, altAGL: null, engineOn: true, gearDown: true, fuel: 0.6 });
    ac.parkingBrake = false;
    const run = (secs, f) => { for (let t = 0; t < secs; t += STEP) { f(ac); ac.update(STEP, weather); } };
    run(6, (a) => { a.controls.throttle = a.groundSpeed < 7 ? 0.35 : 0; a.controls.yaw = 0; a.controls.brakes = 0; });
    run(3, (a) => { a.controls.throttle = a.groundSpeed < 7 ? 0.3 : 0; a.controls.yaw = 0.6; });
    const hRel = ac.heading;
    run(4, (a) => { a.controls.throttle = a.groundSpeed < 7 ? 0.3 : 0; a.controls.yaw = 0; });
    const back = ((ac.heading - hRel + 540) % 360) - 180;
    const turned = ((hRel - 90 + 540) % 360) - 180;
    return { turned, back };
  };
  for (const mode of ['simplified', 'realistic']) {
    const tx = taxi(mode);
    ok(`taxi (${mode === 'simplified' ? 'Easy / Normal' : 'Realistic'}): a pedal turn, let go — she does not swing back toward the old heading`, tx.turned > 8 && tx.back > -2, `turned ${tx.turned.toFixed(1)}°, then ${tx.back.toFixed(1)}° after letting go`);
  }
  const sky = brake('skylark', 10, 1, 10);
  ok('brakes: the Skylark still stops', sky.stop !== null && !sky.crashed, `stopped at ${sky.stop && sky.stop.toFixed(1)} s`);
}

/* ---------------- the take-off roll keeps the runway heading ---------------- */
{
  const THREE = await load('src/vendor/three.module.js');
  const T = await load('src/world/terrain.js');
  const P = await load('src/aircraft/physics.js');
  const { Weather } = await load('src/world/weather.js');
  T.applyMap('kestrel');
  const weather = new Weather();
  weather.load({ time: 'day', condition: 'clear', windSpeedKts: 0, windDirDeg: 0 });
  const STEP = 1 / 60;
  // Full power from a runway start (Easy); a one-second dab of rudder at 25 m/s, then let go.
  P.applyAircraft('a321');
  const ac = new P.Aircraft();
  ac.mode = 'simplified';
  ac.difficulty = 'easy';
  ac.reset({ pos: new THREE.Vector3(-400, 0, 0), headingDeg: 90, speed: 0, altAGL: null, engineOn: true, gearDown: true, fuel: 0.6 });
  ac.parkingBrake = false;
  let tapT = null;
  let res = null;
  for (let t = 0; t < 40 && !res; t += STEP) {
    ac.controls.throttle = 1;
    ac.controls.brakes = 0;
    ac.controls.pitch = 0;
    if (tapT === null && ac.groundSpeed > 25) tapT = t;
    ac.controls.yaw = tapT !== null && t - tapT < 1 ? 0.5 : 0;
    ac.update(STEP, weather);
    if (!ac.onGround || ac.readouts().iasKts > 85) res = { err: ((ac.heading - 90 + 540) % 360) - 180, lat: ac.pos.z };
  }
  ok('take-off roll: a dab of rudder at speed, let go — she comes back to the runway heading (the held heading follows only at taxi speeds)', res && Math.abs(res.err) < 2 && Math.abs(res.lat) < 12, res ? `${res.err.toFixed(1)}° off, ${res.lat.toFixed(1)} m from the line at 85 kt` : 'never got to 85 kt');
}

