// The dev console's commands (src/features/dev-console.js), run without a page.
import { runLine, findPlane, suggest, findTarget, tpTargets } from '../../src/features/dev-console.js';
import { AIRCRAFT } from '../../src/aircraft/types.js';

let pass = 0, fail = 0;
const ok = (name, cond, detail = '') => { if (cond) pass++; else { fail++; console.log('FAIL', name, detail); } };
const p = { unlocked: ['skylark'], credits: 10 };
const sim = { prog: p };

let r = runLine(sim, '/runcmd allaircraft');
ok('allaircraft unlocks every aircraft', r.ok && AIRCRAFT.every((a) => p.unlocked.includes(a.id)), r.text);
ok('allaircraft leaves no military flag behind', !('militaryUnlocked' in p));
r = runLine(sim, 'allaircraft');
ok('works without /runcmd', r.ok && /0 new/.test(r.text), r.text);
r = runLine(sim, '/runcmd credits 5000');
ok('credits sets', r.ok && p.credits === 5000, r.text);
r = runLine(sim, '/runcmd addcredits 1,000');
ok('addcredits adds', r.ok && p.credits === 6000, r.text);
r = runLine(sim, '/runcmd credits lots');
ok('credits rejects a non-number', !r.ok && p.credits === 6000, r.text);
const q = { unlocked: [], credits: 0 };
r = runLine({ prog: q }, '/runcmd unlock A380');
ok('unlock one by id, any case', r.ok && q.unlocked.includes('a380'), r.text);
r = runLine({ prog: q }, '/runcmd unlock nope');
ok('unlock an unknown id fails politely', !r.ok, r.text);
r = runLine(sim, '/runcmd help');
ok('help lists allaircraft', r.ok && /allaircraft/.test(r.text));
r = runLine(sim, '/runcmd fly-to-the-moon');
ok('unknown command says so', !r.ok && /Unknown/.test(r.text));
r = runLine(sim, '/runcmd list');
ok('list names every id', r.ok && AIRCRAFT.every((a) => r.text.includes(a.id)));

// /give (owner, 2026-11-08)
const g = { unlocked: ['skylark'], credits: 0 };
r = runLine({ prog: g }, '/give a320');
ok('/give one plane by id', r.ok && g.unlocked.includes('a320') && /A320|a320/i.test(r.text), r.text);
r = runLine({ prog: g }, '/give a320');
ok('/give again says you have it', r.ok && /already/.test(r.text) && g.unlocked.filter((x) => x === 'a320').length === 1, r.text);
const named = AIRCRAFT.find((a) => a.name && a.name.length > 4 && !/^[a-z0-9]+$/.test(a.name));
r = runLine({ prog: g }, `/give ${named.name.toUpperCase()}`);
ok('/give by name, any case', r.ok && g.unlocked.includes(named.id), `${named.name}: ${r.text}`);
r = runLine({ prog: g }, '/give @s skylark');
ok('/give takes @s like Minecraft', r.ok && /already/.test(r.text), r.text);
r = runLine({ prog: g }, '/give zzzz-no-plane');
ok('/give an unknown plane fails politely', !r.ok && /No plane/.test(r.text), r.text);
r = runLine({ prog: g }, '/give');
ok('/give alone says how', !r.ok && /\/give all/.test(r.text), r.text);
ok('findPlane knows the Javelin before it is earned', findPlane('javelin').hit && findPlane('javelin').hit.id === 'javelin');
const amb = findPlane('a3');
ok('a part of a name that fits several asks which', !amb.hit && amb.many.length > 1, String(amb.many.length));
const h = { unlocked: [], credits: 0 };
r = runLine({ prog: h }, '/give all');
ok('/give all gives every plane, secret ones too', r.ok && AIRCRAFT.every((a) => h.unlocked.includes(a.id)) && AIRCRAFT.some((a) => a.secret), r.text);
r = runLine(sim, '/runcmd help');
ok('help lists /give', /\/give all/.test(r.text) && /\/give <plane>/.test(r.text));

// /tp and the suggestions (owner, 2026-11-08: "press tab to fill in this airport")
const fields = [{ id: 'haven', code: 'XHVN', name: 'Haven International' }, { id: 'gull', code: 'XGUL', name: 'Sennen Cove Strip' }, { id: 'tern', code: 'XTRN', name: 'Harrier Flats Field' }];
const moves = [];
const tsim = { prog: { unlocked: [], credits: 0 }, game: 'flight', settings: { map: 'kestrel' }, worldPreview: { airports: () => fields, active: () => false }, startMode: () => Promise.resolve() };
ok('targets: Nullspire, the World Map fields, the maps', tpTargets(tsim).some((t) => t.fill === 'nullspire') && tpTargets(tsim).some((t) => t.fill === 'XHVN') && tpTargets(tsim).some((t) => t.fill === 'kestrel') && !tpTargets(tsim).some((t) => t.fill === 'world-preview'));
ok('targets: the boat and car maps are not the aeroplane\'s', !tpTargets(tsim).some((t) => t.fill === 'drovers'));
ok('find: by code, any case', findTarget(tsim, 'xhvn').hit?.go.field === 'haven');
ok('find: by name', findTarget(tsim, 'haven international').hit?.go.field === 'haven');
ok('find: a map by id', findTarget(tsim, 'kestrel').hit?.go.map === 'kestrel');
ok('find: nullspire', findTarget(tsim, 'Nullspire').hit?.go.city === true);
let sg = suggest(tsim, '');
ok('suggest: an empty line lists the commands', sg.length >= 4 && sg.some((x) => x.line === '/tp ') && sg.some((x) => x.line === '/give '), sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/t');
ok('suggest: /t → /tp first', sg[0] && sg[0].line === '/tp ', sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/tp ha');
ok('suggest: /tp ha → Haven first', sg[0] && sg[0].line === '/tp XHVN' && /Haven/.test(sg[0].name), sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/tp sennen');
ok('suggest: a name word finds the field (Sennen Cove Strip) and the map', sg.some((x) => x.fill === 'XGUL'), sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/tp ');
ok('suggest: /tp and a space lists places, Nullspire first, at most 8', sg.length === 8 && sg[0].fill === 'nullspire', String(sg.length));
sg = suggest(tsim, '/give jav');
ok('suggest: /give jav → the Javelin', sg[0] && sg[0].line === '/give javelin', sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/give @s a3');
ok('suggest: keeps @s', sg.length && sg.every((x) => x.line.startsWith('/give @s ')), sg.map((x) => x.line).join(','));
sg = suggest(tsim, '/give ');
ok('suggest: /give lists "all" first', sg[0] && sg[0].fill === 'all');
sg = suggest(tsim, '/runcmd cr');
ok('suggest: /runcmd subcommands', sg[0] && sg[0].line === '/runcmd credits ', sg.map((x) => x.line).join(','));
ok('suggest: nothing for a spot', suggest(tsim, '/tp 1200').length === 0);
r = runLine(tsim, '/tp');
ok('/tp alone says how', !r.ok && /Tab/.test(r.text), r.text);
r = runLine(tsim, '/tp nowhere-at-all');
ok('/tp nowhere fails politely', !r.ok && /Nowhere/.test(r.text), r.text);
r = runLine(tsim, '/tp 1200');
ok('/tp one number asks for two', !r.ok && /two numbers/.test(r.text), r.text);
r = runLine(tsim, '/tp 1200 300');
ok('/tp a spot off the World Map, on the ground, says take off first', !r.ok && /take off/.test(r.text), r.text);
const fly = { ...tsim, state: 'flying', aircraft: { onGround: false, crashed: false, pos: { y: 900, set(x, y, z) { moves.push([x, y, z]); } } } };
r = runLine(fly, '/tp 2km -1.5km');
ok('/tp a spot in the air moves you, km read', r.ok && moves.length === 1 && moves[0][0] === 2000 && moves[0][2] === -1500 && moves[0][1] >= 900, `${r.text} ${JSON.stringify(moves)}`);
r = runLine(tsim, '/help');
ok('help lists /tp and Tab', /\/tp <airport/.test(r.text) && /Tab/.test(r.text));
console.log(`dev-console: ${pass}/${pass + fail} passed`);
process.exit(fail ? 1 : 0);
