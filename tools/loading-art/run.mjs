/**
 * The loop behind capture.mjs: for each map, ask the page (page.js) for its
 * picture, save it, and keep where its subject is in the frame.
 *
 * `evalFn(body, timeoutSeconds)` evaluates an async function body inside the
 * running game and returns its value; capture.mjs gives it the headless
 * Chrome's, but anything that can do that will do.
 *
 * The subject's place goes in tools/loading-art/focus.json (merged: a run of
 * a few maps keeps the others') and from it src/ui/loading-focus.js is
 * written, which the loading screen reads so a phone held upright crops each
 * picture round its subject instead of round its middle.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const ROOT = resolve(here, '..', '..');
const FOCUS_JSON = join(here, 'focus.json');
const FOCUS_JS = join(ROOT, 'src', 'ui', 'loading-focus.js');

/** The in-page helper's source, to be evaluated once per page. */
export function pageSource() {
  return readFileSync(join(here, 'page.js'), 'utf8');
}

export async function loadSpots() {
  return (await import(`${pathToFileURL(join(here, 'spots.mjs')).href}?${Date.now()}`)).SPOTS;
}

/** Write src/ui/loading-focus.js from the merged store. */
export function writeFocusModule(store) {
  const ids = Object.keys(store).sort();
  const body = ids.map((id) => `  ${JSON.stringify(id)}: [${store[id][0]}, ${store[id][1]}],`).join('\n');
  writeFileSync(
    FOCUS_JS,
    `/**
 * Where each map's loading picture has its subject (the aeroplane, boat or van, else what the camera
 * looks at), as [x, y] in percent of the picture. A tall narrow screen shows a slice of a 16:9 picture;
 * ui/loading-screen.js centres the slice here.
 *
 * GENERATED by tools/loading-art/capture.mjs from tools/loading-art/focus.json. Do not edit by hand.
 */
export const FOCUS = {
${body}
};
`
  );
}

export async function captureMaps({ evalFn, ids, size, outDir, log = console.log }) {
  const spots = await loadSpots();
  mkdirSync(outDir, { recursive: true });
  const store = existsSync(FOCUS_JSON) ? JSON.parse(readFileSync(FOCUS_JSON, 'utf8')) : {};
  let ok = 0;
  const want = ids && ids.length ? ids : Object.keys(spots);
  for (const id of want) {
    if (!spots[id]) {
      log('NO SPOT', id);
      continue;
    }
    try {
      const r = await evalFn(`return await window.__art(${JSON.stringify(id)}, ${JSON.stringify(spots[id])}, ${JSON.stringify(size)});`, 300);
      writeFileSync(join(outDir, `${id}.jpg`), Buffer.from(r.b64, 'base64'));
      // The vehicle's place in the frame, unless the spot says the picture is about something else.
      store[id] = spots[id].subject || r.focus;
      ok++;
      log('captured', id, `subject at ${r.focus[0]}%, ${r.focus[1]}%`);
    } catch (e) {
      log('FAILED', id, String(e && e.message).slice(0, 200));
    }
  }
  writeFileSync(FOCUS_JSON, JSON.stringify(store, null, 1) + '\n');
  writeFocusModule(store);
  return { ok, total: want.length };
}
