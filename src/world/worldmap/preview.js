/**
 * World Map — Preview: one big sea, several islands, five airports, one map.
 *
 * WHAT THIS IS. The mega-map plan (B/mega-map-plan.md) is one open world made
 * of today's maps placed as islands, with frames, handovers and a floating
 * origin. That engine exists on its own branches (feat/world-*-cont) against a
 * tree 300 commits old, and its main.js half is 1,700 lines that cannot land
 * in the week of a class demo without risking every map. This is the part
 * that CAN land: a playable preview of the open world, behind its own card in
 * the map picker, that replaces nothing.
 *
 * HOW IT FITS IN ONE FRAME. The plan's own precision rule is that nothing
 * simulated or drawn is more than 64 km from the origin. The preview sea is a
 * 120 km box round the hub (every airport within 60 km of it), so it needs no
 * rebase at all: three.js composes each mesh's matrix with the camera's in
 * doubles, the chunks are positioned at their own centres, and float32 at
 * 60 km is 4 mm. One map definition, loaded the way every map is (applyMap,
 * buildWorld), with two differences:
 *
 *   - its terrain has no fixed chunks. The ground is streamed in tiles round
 *     the camera (worldmap/stream.js) inside a per-tier time budget, with
 *     coarser tiles further out and far tiles unloaded;
 *   - which airport is the "airport" — the one the runway, tower, terminal,
 *     stands, ATC, ILS and landing grade are built round — is the one the
 *     player picked to start at. Every other field is drawn by
 *     worldmap/outstation.js. Choosing another start rebuilds the world, the
 *     same as choosing another map.
 *
 * WHY THE GROUND NEVER CHANGES WITH THE START. terrain.js cuts approach lanes
 * and levels the overrun only for the loaded AIRPORT. Every field here sits
 * on authored flat ground (FLATS) that covers its runway, its overruns and
 * its airport layout, and every approach is naturally clear — the placement
 * rules (checkPlacement below, run by the tool and by the test) prove that the
 * height field is the same, to a centimetre, whichever field is loaded. So a
 * field you land at is the ground you saw from the air, whichever one you
 * took off from.
 *
 * Pure: no meshes, no DOM. The data is generated by tools/worldmap/
 * preview-layout.mjs into preview-data.js; never hand-edit that file.
 */

import { PREVIEW_DATA } from './preview-data.js';

/** The map id. Not in MAPS: the flight game's list, the lobbies and every map test stay as they are. */
export const WORLD_PREVIEW_ID = 'world-preview';

/** What the picker calls it. "Preview" is part of the name on purpose. */
export const WORLD_PREVIEW_TITLE = 'World Map — Preview';

export const PREVIEW = PREVIEW_DATA;

/** Airports, by id, in the order the picker lists them (the hub first). */
export const AIRPORTS = PREVIEW.airports;

export function airportById(id) {
  return AIRPORTS.find((a) => a.id === id || a.code === id) || null;
}

/** The hub: where a first visit starts. */
export const HUB_ID = AIRPORTS[0].id;

/** Metres between two airports, runway centre to runway centre. */
export function legM(a, b) {
  const A = typeof a === 'string' ? airportById(a) : a;
  const B = typeof b === 'string' ? airportById(b) : b;
  return Math.hypot(A.x - B.x, A.z - B.z);
}

/** The nearest airport to a point, and how far. */
export function nearestAirport(x, z) {
  let best = null;
  let bd = Infinity;
  for (const a of AIRPORTS) {
    const d = Math.hypot(a.x - x, a.z - z);
    if (d < bd) { bd = d; best = a; }
  }
  return { airport: best, distM: bd };
}

/** Compass heading, degrees clockwise from north (-Z is north), from one point to another. */
export function headingTo(fx, fz, tx, tz) {
  const h = (Math.atan2(tx - fx, -(tz - fz)) * 180) / Math.PI;
  return (h + 360) % 360;
}

/**
 * The one definition object. getMap() hands back this same object every
 * time (maps.js registerExtraMap), so `MAP === previewDef()` holds across a
 * rebuild; setDeparture() rewrites the parts that follow the start.
 */
let DEF = null;

function deepCopy(v) {
  return JSON.parse(JSON.stringify(v));
}

export function previewDef() {
  if (DEF) return DEF;
  DEF = makeDef(PREVIEW);
  setDeparture(HUB_ID);
  return DEF;
}

/** A definition from layout data (the tool builds candidates with this). */
export function makeDef(P) {
  const def = {
    id: WORLD_PREVIEW_ID,
    preview: true,
    worldPreview: true,
    title: WORLD_PREVIEW_TITLE,
    name: '',
    subtitle: '',
    blurb:
      'One big sea with five airports on its islands — a hub, two short hops, a grass strip and ' +
      'a long haul over open water. A preview of the World Map: the ground streams in as you fly.',
    difficulty: 2,
    difficultyLabel: 'Open sea',
    seaFloor: P.seaFloor,
    islands: deepCopy(P.islands),
    // No fixed terrain: worldmap/stream.js lays it round the camera.
    chunks: [],
    streamTerrain: true,
    flats: deepCopy(P.flats),
    waters: { roads: deepCopy(P.roads) },
    palette: deepCopy(P.palette),
    scenery: deepCopy(P.scenery),
    weather: deepCopy(P.weather),
    features: {},
    airport: null,
    parking: false,
    _data: P,
  };
  setDepartureOn(def, P.airports[0].id);
  return def;
}

/** The field the world is currently built round. */
export function departure() {
  return previewDef()._departure;
}

/**
 * Build the world round this airport next time the map is applied.
 *
 * A fresh `airport` object every time, because airport-layout.js memoises on
 * the object's identity and the car park flag is not part of its key.
 */
export function setDeparture(id) {
  return setDepartureOn(DEF || previewDef(), id);
}

/** The same, on any definition made by makeDef. */
export function setDepartureOn(d, id) {
  const list = (d._data || PREVIEW).airports;
  const a = list.find((x) => x.id === id || x.code === id) || list[0];
  d._departure = a;
  d.name = a.place;
  d.subtitle = `${WORLD_PREVIEW_TITLE} · from ${a.code}`;
  d.parking = !!a.parking;
  d.airport = {
    elev: a.elev,
    headingDeg: 90,
    runway: { cx: a.x, cz: a.z, length: a.length, halfWidth: a.halfWidth },
    // No pad: the field's level ground is an authored flat (see the header),
    // which is the same whichever field is loaded.
    pad: null,
  };
  if (a.carrier) d.carrier = { x: a.carrier.x, z: a.carrier.z };
  else delete d.carrier;
  // The bounding boxes terrain.js caches on the waters block are per map, and
  // the map has not changed — but its airport has, and the harbour/road
  // caches are rebuilt from scratch on the next applyMap to be safe.
  if (d.waters) delete d.waters._ready;
  return d;
}

/* ------------------------------------------------------------------ */
/* The placement rules                                                 */
/* ------------------------------------------------------------------ */

/** Three degrees, and how far under that surface the ground has to stay. */
const GLIDE_TAN = Math.tan((3 * Math.PI) / 180);
const GLIDE_MARGIN = 12;
const TOUCHDOWN_INSET = 200;

/**
 * Every rule a field has to pass, measured against the live height field.
 *
 * `T` is terrain.js (applyMap already called with this def), `layoutFn`
 * airport-layout.js's airportLayout (optional: the departure's layout must fit
 * its flat). Returns [{ rule, airport, pass, detail }]. The tool runs this
 * while it places the fields and the node test runs it on what shipped.
 */
export function checkAirport(T, a, opts = {}) {
  const D = opts.data || PREVIEW;
  const out = [];
  const add = (rule, pass, detail) => out.push({ rule, airport: a.code, pass: !!pass, detail });
  const hw = a.halfWidth;
  const L = a.length;

  // 1. A flat site: the runway is level at field elevation along all of it.
  let worst = 0;
  for (let u = -L / 2; u <= L / 2; u += 25) {
    for (const v of [-hw, 0, hw]) worst = Math.max(worst, Math.abs(T.heightAt(a.x + u, a.z + v) - a.elev));
  }
  add('runway level', worst < 0.15, `worst ${worst.toFixed(2)} m off ${a.elev} m`);

  // ...and the ground it was levelled from was already nearly flat, so the
  // field is somewhere a field would be built, not a bulldozed hilltop.
  if (opts.natural) {
    const n = opts.natural;
    add('site naturally flat', n.cutFill <= (a.kind === 'ga' ? 10 : 14) && n.slope <= 0.06,
      `natural ground ${n.min.toFixed(1)}..${n.max.toFixed(1)} m (cut/fill ${n.cutFill.toFixed(1)} m), mean slope ${(n.slope * 100).toFixed(1)}%`);
  }

  // 2. Into the prevailing wind: the runway axis within 30 degrees of it.
  const wind = a.prevailingDeg;
  const axis = 90;
  const off = Math.abs(((wind - axis) % 180 + 180) % 180);
  const offAxis = Math.min(off, 180 - off);
  add('runway into the prevailing wind', offAxis <= 30, `wind ${wind}°, runway 09/27, ${offAxis.toFixed(0)}° off the axis`);

  // 3. Clear approaches, both ends: the ground stays GLIDE_MARGIN under the
  //    three-degree path to touchdown, out to 6 km, over a 300 m wide lane.
  let tightest = Infinity;
  let at = '';
  for (const end of [-1, 1]) {
    const tx = a.x + end * (L / 2 - TOUCHDOWN_INSET);
    for (let d = 300; d <= 6000; d += 50) {
      const x = tx + end * d;
      for (const v of [-150, -75, 0, 75, 150]) {
        const g = T.heightAt(x, a.z + v);
        const ceiling = a.elev + Math.max(3, d * GLIDE_TAN - GLIDE_MARGIN) + Math.max(0, Math.abs(v) - 90) * 0.5;
        const room = ceiling - Math.max(g, 0);
        if (room < tightest) { tightest = room; at = `${end < 0 ? '09' : '27'} approach, ${(d / 1000).toFixed(2)} km out, ${v} m off`; }
      }
    }
  }
  add('approaches clear', tightest >= 0, `tightest ${tightest.toFixed(1)} m of room (${at})`);

  // 4. Something to drive to: a town on the same island, connected by road.
  const town = D.towns.find((t) => t.airport === a.id);
  const td = town ? Math.hypot(town.cx - a.x, town.cz - a.z) : Infinity;
  add('a town nearby', town && td <= 5000 && town.count >= 8, town ? `${town.name}, ${(td / 1000).toFixed(1)} km, ${town.count} buildings` : 'no town');
  const road = D.roads.find((r) => r.airport === a.id);
  if (!road) add('a road from the field to the town', false, 'no road');
  else {
    const p = road.path;
    const first = p[0];
    const last = p[p.length - 1];
    const apron = a.apron || { x: a.x, z: a.z };
    const dA = Math.hypot(first[0] - apron.x, first[1] - apron.z);
    const dT = town ? Math.hypot(last[0] - town.cx, last[1] - town.cz) : Infinity;
    let dry = true;
    let grade = 0;
    for (let i = 0; i < p.length; i++) {
      if (T.heightAt(p[i][0], p[i][1]) < 0.5) dry = false;
      if (i) grade = Math.max(grade, Math.abs(p[i][2] - p[i - 1][2]) / Math.max(1, Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1])));
    }
    add('a road from the field to the town', dA <= 250 && dT <= town.radius && dry && grade <= 0.1,
      `starts ${dA.toFixed(0)} m from the apron, ends ${dT.toFixed(0)} m from the town centre, dry ${dry}, steepest ${(grade * 100).toFixed(1)}%`);
  }

  // 5. The car park rule (owner, Oct 25): commercial fields only.
  const commercial = a.kind === 'hub' || a.kind === 'regional';
  add('car park only at a commercial field', !!a.parking === commercial, `${a.kind}, parking ${!!a.parking}`);

  // 6. No town, road or other flat on the runway or in its lanes.
  let lane = 0;
  for (const t of D.towns) {
    const along = Math.abs(t.cx - a.x);
    const across = Math.abs(t.cz - a.z);
    if (along < L / 2 + 6000 && across < t.radius + 400) lane++;
  }
  add('no town in the runway or its approach lanes', lane === 0, `${lane} towns in the lanes`);

  // 7. The departure's own airport layout stands on the field's flat.
  if (opts.layout) {
    const lay = opts.layout;
    const site = a.site;
    const pieces = [...(lay.pavement || []), ...(lay.buildings || [])];
    let outside = 0;
    for (const r of pieces) {
      if (r.x0 < site.x0 || r.x1 > site.x1 || r.z0 < site.z0 || r.z1 > site.z1) outside++;
    }
    add('the airport layout fits its site', outside === 0 && (lay.dropped || []).length === 0,
      `${pieces.length} pieces, ${outside} outside the site, ${(lay.dropped || []).length} dropped`);
  }
  return out;
}

/** Rules about the network as a whole: spacing, short hops, one long haul, precision. */
export function checkNetwork(D = PREVIEW) {
  const out = [];
  const add = (rule, pass, detail) => out.push({ rule, airport: '*', pass: !!pass, detail });
  const A = D.airports;
  const byCode = (c) => A.find((x) => x.code === c);
  add('3 to 5 airports', A.length >= 3 && A.length <= 5, `${A.length}`);
  let minPair = Infinity;
  let maxPair = 0;
  let pairs = [];
  for (let i = 0; i < A.length; i++) {
    for (let j = i + 1; j < A.length; j++) {
      const d = legM(A[i], A[j]);
      pairs.push({ a: A[i].code, b: A[j].code, km: d / 1000 });
      minPair = Math.min(minPair, d);
      maxPair = Math.max(maxPair, d);
    }
  }
  add('fields spaced apart (20 km or more)', minPair >= 20000, `closest pair ${(minPair / 1000).toFixed(1)} km`);
  const hub = A[0];
  const short = A.slice(1).filter((b) => legM(hub, b) >= 20000 && legM(hub, b) <= 40000);
  add('short hops from the hub (20-40 km, 6-10 min in a Skylark)', short.length >= 2,
    short.map((b) => `${b.code} ${(legM(hub, b) / 1000).toFixed(1)} km`).join(', '));
  add('one long haul (90 km or more, both ends airliner fields)', pairs.some((p) => p.km >= 90 &&
    [p.a, p.b].every((c) => (byCode(c).length >= 1600))), pairs.filter((p) => p.km >= 90).map((p) => `${p.a}-${p.b} ${p.km.toFixed(1)} km`).join(', ') || 'none');
  let far = 0;
  for (const a of A) far = Math.max(far, Math.hypot(a.x, a.z) + a.length / 2);
  add('every field within 60 km of the origin (float32 under 4 mm)', far <= 60000, `farthest runway end ${(far / 1000).toFixed(1)} km`);
  const codes = new Set(A.map((a) => a.code));
  add('codes unique and X-prefixed', codes.size === A.length && A.every((a) => /^X[A-Z]{3}$/.test(a.code)), [...codes].join(' '));
  return out;
}
