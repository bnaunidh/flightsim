/** Three degrees, and how far under that surface the ground has to stay. */
const GLIDE_TAN = Math.tan((3 * Math.PI) / 180);
const GLIDE_MARGIN = 12;
const TOUCHDOWN_INSET = 200;

/**
 * Every rule a field has to pass, measured against the live height field.
 *
 * `T` is terrain.js (applyMap already called with this def), `layoutFn`
 * airport-layout.js's airportLayout (optional: the departure's layout must fit
 * its flat). Returns [{ rule, airport, pass, detail }]. The tool runs this
 * while it places the fields and the node test runs it on what shipped.
 */
export function checkAirport(T, a, opts = {}) {
  const D = opts.data || PREVIEW;
  const out = [];
  const add = (rule, pass, detail) => out.push({ rule, airport: a.code, pass: !!pass, detail });
  const hw = a.halfWidth;
  const L = a.length;

  // 1. A flat site: the runway is level at field elevation along all of it.
  let worst = 0;
  for (let u = -L / 2; u <= L / 2; u += 25) {
    for (const v of [-hw, 0, hw]) worst = Math.max(worst, Math.abs(T.heightAt(a.x + u, a.z + v) - a.elev));
  }
  add('runway level', worst < 0.15, `worst ${worst.toFixed(2)} m off ${a.elev} m`);

  // ...and the ground it was levelled from was already nearly flat, so the
  // field is somewhere a field would be built, not a bulldozed hilltop.
  if (opts.natural) {
    const n = opts.natural;
    add('site naturally flat', n.cutFill <= (a.kind === 'ga' ? 10 : 14) && n.slope <= 0.06,
      `natural ground ${n.min.toFixed(1)}..${n.max.toFixed(1)} m (cut/fill ${n.cutFill.toFixed(1)} m), mean slope ${(n.slope * 100).toFixed(1)}%`);
  }

  // 2. Into the prevailing wind: the runway axis within 30 degrees of it.
  const wind = a.prevailingDeg;
  const axis = 90;
  const off = Math.abs(((wind - axis) % 180 + 180) % 180);
  const offAxis = Math.min(off, 180 - off);
  add('runway into the prevailing wind', offAxis <= 30, `wind ${wind}°, runway 09/27, ${offAxis.toFixed(0)}° off the axis`);

  // 3. Clear approaches, both ends: the ground stays GLIDE_MARGIN under the
  //    three-degree path to touchdown, out to 6 km, over a 300 m wide lane.
  let tightest = Infinity;
  let at = '';
  for (const end of [-1, 1]) {
    const tx = a.x + end * (L / 2 - TOUCHDOWN_INSET);
    for (let d = 300; d <= 6000; d += 50) {
      const x = tx + end * d;
      for (const v of [-150, -75, 0, 75, 150]) {
        const g = T.heightAt(x, a.z + v);
        const ceiling = a.elev + Math.max(3, d * GLIDE_TAN - GLIDE_MARGIN) + Math.max(0, Math.abs(v) - 90) * 0.5;
        const room = ceiling - Math.max(g, 0);
        if (room < tightest) { tightest = room; at = `${end < 0 ? '09' : '27'} approach, ${(d / 1000).toFixed(2)} km out, ${v} m off`; }
      }
    }
  }
  add('approaches clear', tightest >= 0, `tightest ${tightest.toFixed(1)} m of room (${at})`);

  // 4. Something to drive to: a town on the same island, connected by road.
  const town = D.towns.find((t) => t.airport === a.id);
  const td = town ? Math.hypot(town.cx - a.x, town.cz - a.z) : Infinity;
  add('a town nearby', town && td <= 5000 && town.count >= 8, town ? `${town.name}, ${(td / 1000).toFixed(1)} km, ${town.count} buildings` : 'no town');
  const road = D.roads.find((r) => r.airport === a.id);
  if (!road) add('a road from the field to the town', false, 'no road');
  else {
    const p = road.path;
    const first = p[0];
    const last = p[p.length - 1];
    const apron = a.apron || { x: a.x, z: a.z };
    const dA = Math.hypot(first[0] - apron.x, first[1] - apron.z);
    const dT = town ? Math.hypot(last[0] - town.cx, last[1] - town.cz) : Infinity;
    let dry = true;
    let grade = 0;
    for (let i = 0; i < p.length; i++) {
      if (T.heightAt(p[i][0], p[i][1]) < 0.5) dry = false;
      if (i) grade = Math.max(grade, Math.abs(p[i][2] - p[i - 1][2]) / Math.max(1, Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1])));
    }
    add('a road from the field to the town', dA <= 250 && dT <= town.radius && dry && grade <= 0.1,
      `starts ${dA.toFixed(0)} m from the apron, ends ${dT.toFixed(0)} m from the town centre, dry ${dry}, steepest ${(grade * 100).toFixed(1)}%`);
  }

  // 5. The car park rule (owner, Oct 25): commercial fields only.
  const commercial = a.kind === 'hub' || a.kind === 'regional';
  add('car park only at a commercial field', !!a.parking === commercial, `${a.kind}, parking ${!!a.parking}`);

  // 6. No town, road or other flat on the runway or in its lanes.
  let lane = 0;
  for (const t of D.towns) {
    const along = Math.abs(t.cx - a.x);
    const across = Math.abs(t.cz - a.z);
    if (along < L / 2 + 6000 && across < t.radius + 400) lane++;
  }
  add('no town in the runway or its approach lanes', lane === 0, `${lane} towns in the lanes`);

  // 7. The departure's own airport layout stands on the field's flat.
  if (opts.layout) {
    const lay = opts.layout;
    const site = a.site;
    const pieces = [...(lay.pavement || []), ...(lay.buildings || [])];
    let outside = 0;
    for (const r of pieces) {
      if (r.x0 < site.x0 || r.x1 > site.x1 || r.z0 < site.z0 || r.z1 > site.z1) outside++;
    }
    add('the airport layout fits its site', outside === 0 && (lay.dropped || []).length === 0,
      `${pieces.length} pieces, ${outside} outside the site, ${(lay.dropped || []).length} dropped`);
  }
  return out;
}

/** Rules about the network as a whole: size, regions, spacing, the mix of fields, the long hauls. */
export function checkNetwork(D = PREVIEW) {
  const out = [];
  const add = (rule, pass, detail) => out.push({ rule, airport: '*', pass: !!pass, detail });
  const A = D.airports;
  const byCode = (c) => A.find((x) => x.code === c);
  add('14 to 18 airports', A.length >= 14 && A.length <= 18, `${A.length}`);
  add('50 islands or more', D.islands.length >= 50, `${D.islands.length}`);
  // The sea's size: the box round every island.
  let x0 = Infinity;
  let x1 = -Infinity;
  let z0 = Infinity;
  let z1 = -Infinity;
  for (const i of D.islands) {
    x0 = Math.min(x0, i.cx - i.radius); x1 = Math.max(x1, i.cx + i.radius);
    z0 = Math.min(z0, i.cz - i.radius); z1 = Math.max(z1, i.cz + i.radius);
  }
  add('a sea about 400 km across (350 km or more each way)', x1 - x0 >= 350000 && z1 - z0 >= 350000,
    `${((x1 - x0) / 1000).toFixed(0)} x ${((z1 - z0) / 1000).toFixed(0)} km`);
  add('everything inside 200 km of the middle on both axes', Math.max(-x0, x1, -z0, z1) <= 200000,
    `furthest coast ${(Math.max(-x0, x1, -z0, z1) / 1000).toFixed(1)} km`);
  const regions = D.regions || [];
  const withFields = regions.filter((g) => A.some((a) => a.region === g.id));
  add('five regions or more, each with a field', regions.length >= 5 && withFields.length === regions.length,
    regions.map((g) => `${g.name} ${A.filter((a) => a.region === g.id).length}`).join(', '));
  add('every island belongs to a region', D.islands.every((i) => regions.some((g) => g.id === i.region)), '');
  let minPair = Infinity;
  const pairs = [];
  for (let i = 0; i < A.length; i++) {
    for (let j = i + 1; j < A.length; j++) {
      const d = legM(A[i], A[j]);
      pairs.push({ a: A[i].code, b: A[j].code, km: d / 1000 });
      minPair = Math.min(minPair, d);
    }
  }
  add('fields spaced apart (20 km or more)', minPair >= 20000, `closest pair ${(minPair / 1000).toFixed(1)} km`);
  const hub = A[0];
  const short = A.slice(1).filter((b) => legM(hub, b) >= 20000 && legM(hub, b) <= 40000);
  add('short hops from the hub (20-40 km, 6-10 min in a Skylark)', short.length >= 2,
    short.map((b) => `${b.code} ${(legM(hub, b) / 1000).toFixed(1)} km`).join(', '));
  const big = A.filter((a) => a.length >= 3000 && a.halfWidth * 2 >= 45 && a.kind === 'hub');
  add('two or three big internationals (3,000 m by 45 m or more: A380, 747, C-17)', big.length >= 2 && big.length <= 3,
    big.map((a) => `${a.code} ${a.length} x ${a.halfWidth * 2} m`).join(', '));
  const regional = A.filter((a) => a.kind === 'regional');
  add('several regionals (four or more)', regional.length >= 4, regional.map((a) => a.code).join(' '));
  const strips = A.filter((a) => a.kind === 'ga');
  const unpaved = strips.filter((a) => a.surface === 'grass' || a.surface === 'gravel');
  add('light-aircraft strips (four or more, two or more of them grass or gravel)', strips.length >= 4 && unpaved.length >= 2,
    strips.map((a) => `${a.code} ${a.length} m ${a.surface || 'tarmac'}`).join(', '));
  const remote = A.filter((a) => a.kind === 'remote');
  const remoteOk = remote.filter((r) => r.length >= 2800 && A.every((b) => b === r || legM(r, b) >= 140000));
  add('a remote long-haul-only field (2,800 m, 140 km or more from every other field)', remote.length >= 1 && remoteOk.length === remote.length,
    remote.map((r) => `${r.code} ${r.length} m, nearest ${(Math.min(...A.filter((b) => b !== r).map((b) => legM(r, b))) / 1000).toFixed(0)} km`).join(', ') || 'none');
  const airliner = (c) => byCode(c).length >= 1600;
  const longest = pairs.filter((p) => airliner(p.a) && airliner(p.b)).sort((a, b) => b.km - a.km)[0];
  add('a long haul of 300 km or more between airliner fields', longest && longest.km >= 300, longest ? `${longest.a}-${longest.b} ${longest.km.toFixed(1)} km` : 'none');
  const pads = (D.heliports || []);
  add('heliports away from the fields (three or more)', pads.length >= 3, pads.map((p) => `${p.name} (${p.kind})`).join(', '));
  const codes = new Set(A.map((a) => a.code));
  add('codes unique and X-prefixed', codes.size === A.length && A.every((a) => /^X[A-Z]{3}$/.test(a.code)), [...codes].join(' '));
  const ids = new Set(A.map((a) => a.id));
  add('ids unique', ids.size === A.length, '');
  return out;
}

/** The region a point is in: the nearest region whose field or island is nearest. */
export function regionAt(x, z, D = PREVIEW) {
  let best = null;
  let bd = Infinity;
  for (const i of D.islands) {
    const d = Math.hypot(x - i.cx, z - i.cz) - i.radius;
    if (d < bd) { bd = d; best = i.region; }
  }
  return (D.regions || []).find((g) => g.id === best) || null;
}
