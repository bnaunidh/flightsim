/**
 * World Map — Preview: one big sea, several islands, five airports, one map.
 *
 * WHAT THIS IS. The mega-map plan (B/mega-map-plan.md) is one open world made
 * of today's maps placed as islands, with frames, handovers and a floating
 * origin. That engine exists on its own branches (feat/world-*-cont) against a
 * tree 300 commits old, and its main.js half is 1,700 lines that cannot land
 * in the week of a class demo without risking every map. This is the part
 * that CAN land: a playable preview of the open world, behind its own card in
 * the map picker, that replaces nothing.
 *
 * HOW IT FITS IN ONE FRAME. The sea is a 400 km box round the hub (wave 17;
 * it was 120 km). The simulation is in JavaScript numbers, float64, so it
 * needs no rebase. Drawing does: three.js composes each mesh's matrix with
 * the camera's in doubles and every tile, field and tree pool sits at its own
 * local origin, but the shaders' world-space sums are float32, 1.6 cm a step
 * at 200 km. So the draw has a floating origin (render/render-origin.js):
 * for the length of each frame the scene is moved so the camera is near
 * (0, 0), and put back afterwards. One map definition, loaded the way every
 * map is (applyMap, buildWorld), with two differences:
 *
 *   - its terrain has no fixed chunks. The ground is streamed in tiles round
 *     the camera (worldmap/stream.js) inside a per-tier time budget, with
 *     coarser tiles further out and far tiles unloaded;
 *   - which airport is the "airport" — the one the runway, tower, terminal,
 *     stands, ATC, ILS and landing grade are built round — is the one the
 *     player picked to start at. Every other field is drawn by
 *     worldmap/outstation.js. Choosing another start rebuilds the world, the
 *     same as choosing another map.
 *
 * WHY THE GROUND NEVER CHANGES WITH THE START. terrain.js cuts approach lanes
 * and levels the overrun only for the loaded AIRPORT. Every field here sits
 * on authored flat ground (FLATS) that covers its runway, its overruns and
 * its airport layout, and every approach is naturally clear — the placement
 * rules (checkPlacement below, run by the tool and by the test) prove that the
 * height field is the same, to a centimetre, whichever field is loaded. So a
 * field you land at is the ground you saw from the air, whichever one you
 * took off from.
 *
 * Pure: no meshes, no DOM. The data is generated by tools/worldmap/
 * preview-layout.mjs into preview-data.js; never hand-edit that file.
 */

import { PREVIEW_DATA } from './preview-data.js';

/** The map id. Not in MAPS: the flight game's list, the lobbies and every map test stay as they are. */
export const WORLD_PREVIEW_ID = 'world-preview';

/** What the picker calls it. "Preview" is part of the name on purpose. */
export const WORLD_PREVIEW_TITLE = 'World Map — Preview';

export const PREVIEW = PREVIEW_DATA;

/** Airports, by id, in the order the picker lists them (the hub first). */
export const AIRPORTS = PREVIEW.airports;

export function airportById(id) {
  return AIRPORTS.find((a) => a.id === id || a.code === id) || null;
}

/** The hub: where a first visit starts. */
export const HUB_ID = AIRPORTS[0].id;

/** Metres between two airports, runway centre to runway centre. */
export function legM(a, b) {
  const A = typeof a === 'string' ? airportById(a) : a;
  const B = typeof b === 'string' ? airportById(b) : b;
  return Math.hypot(A.x - B.x, A.z - B.z);
}

/** The nearest airport to a point, and how far. */
export function nearestAirport(x, z) {
  let best = null;
  let bd = Infinity;
  for (const a of AIRPORTS) {
    const d = Math.hypot(a.x - x, a.z - z);
    if (d < bd) { bd = d; best = a; }
  }
  return { airport: best, distM: bd };
}

/** Compass heading, degrees clockwise from north (-Z is north), from one point to another. */
export function headingTo(fx, fz, tx, tz) {
  const h = (Math.atan2(tx - fx, -(tz - fz)) * 180) / Math.PI;
  return (h + 360) % 360;
}

/**
 * The one definition object. getMap() hands back this same object every
 * time (maps.js registerExtraMap), so `MAP === previewDef()` holds across a
 * rebuild; setDeparture() rewrites the parts that follow the start.
 */
let DEF = null;

function deepCopy(v) {
  return JSON.parse(JSON.stringify(v));
}

export function previewDef() {
  if (DEF) return DEF;
  DEF = makeDef(PREVIEW);
  setDeparture(HUB_ID);
  return DEF;
}

/** A definition from layout data (the tool builds candidates with this). */
export function makeDef(P) {
  const def = {
    id: WORLD_PREVIEW_ID,
    preview: true,
    worldPreview: true,
    title: WORLD_PREVIEW_TITLE,
    name: '',
    subtitle: '',
    blurb:
      `A 400 km sea in six regions — a mainland with mountains and a capital, an archipelago, cold northern rocks, ` +
      `flat sandy cays and a remote outpost — with ${P.airports.length} airports from grass strips to long-haul internationals. ` +
      'A preview of the World Map: the ground streams in as you fly.',
    difficulty: 2,
    difficultyLabel: 'Open sea',
    seaFloor: P.seaFloor,
    islands: deepCopy(P.islands),
    // No fixed terrain: worldmap/stream.js lays it round the camera.
    chunks: [],
    streamTerrain: true,
    flats: deepCopy(P.flats),
    waters: { roads: deepCopy(P.roads) },
    palette: deepCopy(P.palette),
    scenery: deepCopy(P.scenery),
    weather: deepCopy(P.weather),
    features: {},
    airport: null,
    parking: false,
    _data: P,
  };
  setDepartureOn(def, P.airports[0].id);
  return def;
}

/** The field the world is currently built round. */
export function departure() {
  return previewDef()._departure;
}

/**
 * Build the world round this airport next time the map is applied.
 *
 * A fresh `airport` object every time, because airport-layout.js memoises on
 * the object's identity and the car park flag is not part of its key.
 */
export function setDeparture(id) {
  return setDepartureOn(DEF || previewDef(), id);
}

/** The same, on any definition made by makeDef. */
export function setDepartureOn(d, id) {
  const list = (d._data || PREVIEW).airports;
  const a = list.find((x) => x.id === id || x.code === id) || list[0];
  d._departure = a;
  d.name = a.place;
  d.subtitle = `${WORLD_PREVIEW_TITLE} · from ${a.code}`;
  d.parking = !!a.parking;
  d.airport = {
    elev: a.elev,
    headingDeg: 90,
    runway: { cx: a.x, cz: a.z, length: a.length, halfWidth: a.halfWidth },
    // A grass or gravel strip is drawn as one by airport.js (nothing else reads it).
    surface: a.surface || 'tarmac',
    // No pad: the field's level ground is an authored flat (see the header),
    // which is the same whichever field is loaded.
    pad: null,
  };
  // The helipads: the departure's own pad is THE field pad (spawns.js's
  // { pad: 'field' }, the helicopter's first choice), then every other pad
  // nearest first, so the Free Flight picker's few entries are the ones
  // round where you are starting rather than the hub's.
  const src = ((d._data || PREVIEW).scenery || {}).pads || [];
  if (d.scenery && src.length) {
    const mine = `field-${a.id}`;
    d.scenery.pads = src
      .map((p) => (p.id === mine ? { ...p, id: 'field', name: `${a.name} Pad` } : { ...p }))
      .sort((p, q) => (p.id === 'field' ? -1 : q.id === 'field' ? 1 : Math.hypot(p.x - a.x, p.z - a.z) - Math.hypot(q.x - a.x, q.z - a.z)));
  }
  if (a.carrier) d.carrier = { x: a.carrier.x, z: a.carrier.z };
  else delete d.carrier;
  // The bounding boxes terrain.js caches on the waters block are per map, and
  // the map has not changed — but its airport has, and the harbour/road
  // caches are rebuilt from scratch on the next applyMap to be safe.
  if (d.waters) delete d.waters._ready;
  return d;
}

